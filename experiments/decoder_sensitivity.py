    result={'config':CONFIG,'seeds':{}}
    for seed in SEEDS:
        folder=R/f'seed_{seed}';folder.mkdir(exist_ok=True);cnn=CNNBaseline(CFG);cnn.load_state_dict(torch.load('representation_results/cnn.pt',weights_only=True));cnn.encoder.frontend=RelativeFloorLogMel(CFG,.001);cnn.eval()
        for p in cnn.parameters():p.requires_grad_(False)
        tok,meta,system=reference(seed,cnn);adapter=current_adapter(seed);valz,valcnn=inputs(cnn,adapter,vx);valt=tok(valz)['codes']
        fit=torch.tensor(meta['gate_validation']['fit_recordings']);fit=torch.cat([fit,fit+184]);fmask=torch.zeros(len(vy),dtype=torch.bool);fmask[fit]=True;diag=(~fmask).repeat_interleave(4)
        cases={}
        for case,(x,y) in scenarios.items():
            z,b=inputs(cnn,adapter,x);t=tok(z)['codes'];path=Path(f'encoder_results/seed_{seed}/{case}_branches.json');text=path.read_text();rows=json.loads(text)
            policy={'route':torch.tensor([[len(a)==10 for a in row['choices']] for row in rows]),'accept':torch.tensor([row['accepted_positions'] for row in rows]).flatten()}
            cases[case]=(z,(b/system.temperatures['cnn']).softmax(-1),t,y,policy)
            (folder/f'{case}_branches.json').write_text(text)
        output={'models':{},'validation_signal':{}};models={};trigger=False
        for name in ['original_joint','original_aligned']:
            model=ConditionedNCM(copy.deepcopy(tok));model.load_state_dict(torch.load(f'alignment_results/seed_{seed}/{name}.pt',weights_only=True));model.eval();models[name]=model
            normal=predictions(model,valz,valt,'generated')[0];acc=float((normal.argmax(-1)[diag]==vy.flatten()[diag]).float().mean());signals={}
            for mode in ['oracle1','oracle2','oracle_all']:
                a=predictions(model,valz,valt,mode)[0];signals[mode]=float((a.argmax(-1)[diag]==vy.flatten()[diag]).float().mean())-acc
            output['validation_signal'][name]={'generated_digit_accuracy':acc,'oracle_delta':signals};trigger |= max(signals.values())>=.005
        output['training_trigger']=bool(trigger);print(seed,'validation signal',output['validation_signal'],'train',trigger,flush=True)
        # Decision is made on validation diagnostics before test audit/training.
        if trigger:
            trainz,_=inputs(cnn,adapter,tx);train_target=tok(trainz)['codes']
            with torch.inference_mode():
                taps=extract(cnn,tx);local=tok.project(taps['final']);base=(cnn.head(taps['final'])/system.temperatures['cnn']).softmax(-1);proxy=(system.verifier(local)/system.temperatures['local']).softmax(-1)
                gate=system.gate.score(gate_features(base,proxy,tx.reshape(-1,2400).square().mean(-1).sqrt(),local));rank_mask=(gate>=system.route_cutoff)&(gate>=system.accept_cutoff)
            torch.manual_seed(seed);model=ConditionedNCM(copy.deepcopy(tok));opt=torch.optim.AdamW(model.parameters(),lr=.001)
            loader=DataLoader(TensorDataset(trainz,ty.flatten(),rank_mask,*train_target),batch_size=128,shuffle=True,generator=torch.Generator().manual_seed(seed));history=[];start=time.perf_counter()
            for epoch in range(16):
                model.train();losses=[]
                for z,y,mask,*target in loader:
                    opt.zero_grad(set_to_none=True);loss=recognition_loss(model,z,y,target,mask);loss.backward();torch.nn.utils.clip_grad_norm_(model.parameters(),1.);opt.step();losses.append(float(loss.detach()))
                history.append(float(np.mean(losses)));print(seed,'recognition',epoch+1,history[-1],flush=True)
            model.eval();torch.save(model.state_dict(),folder/'recognition.pt');models['recognition']=model;output['training']={'history':history,'seconds':time.perf_counter()-start,'ranked_training_digits':int(rank_mask.sum())}
        for name,model in models.items():
            mf=folder/name;mf.mkdir(exist_ok=True)
            if name=='recognition':temp=ap.temperature(model(valz)['digit_logits'][-1].reshape(-1,4,10)[fit].flatten(0,1),vy[fit].flatten())
