                row['cases'][case]=audit(model,z,b,t,y,policy,temp,mf,case)
                with torch.inference_mode():
                    p=(predictions(model,z,t,'generated')[0]/temp).softmax(-1);mix=b.clone();mix[policy['accept']]=(1-alpha)*b[policy['accept']]+alpha*p[policy['accept']]
                    row['cases'][case]['validation_selected_fusion']=protected_metrics(mix,y,policy)[0]
                # Prediction-only latency: no oracle construction/labels in timed path.
                x=scenarios[case][0];times=[]
                with torch.inference_mode():
                    for events in x:
                        start=time.perf_counter();taps=extract(cnn,events[None]);local=tok.project(taps['final']);bp=(cnn.head(taps['final'])/system.temperatures['cnn']).softmax(-1);proxy=(system.verifier(local)/system.temperatures['local']).softmax(-1);g=system.gate.score(gate_features(bp,proxy,events.square().mean(-1).sqrt(),local));route=g>=system.route_cutoff;accept=route&(g>=system.accept_cutoff)
                        if accept.any():bp[accept]=(model(adapter(taps['final'][accept]))['digit_logits'][-1]/temp).softmax(-1)
                        possibility_tree(bp,route,5);times.append((time.perf_counter()-start)*1000)
