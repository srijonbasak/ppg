@torch.inference_mode()
def inputs(cnn,adapter,x):
    taps=extract(cnn,x);anchor=adapter(taps['final']);base=cnn.head(taps['final'])
    return anchor,base

@torch.inference_mode()
def predictions(model,z,target,name):
    parts=[];cs=[[],[],[]];prefix=[[],[],[]]
    for o in range(0,len(z),128):
        a=z[o:o+128];t=[v[o:o+128] for v in target]
        if name=='generated':out=intervene(model,a)
        elif name.startswith('fixed'):
            normal=intervene(model,a);l=int(name[-1]);out=intervene(model,a,t,[l],fixed=normal['codes'])
        elif name.startswith('perturb'):
            normal=intervene(model,a);out=intervene(model,a,fixed=normal['codes'],perturb=int(name[-1]))
        else:out=intervene(model,a,t,[0,1,2] if name=='oracle_all' else [int(name[-1])])
        parts.append(out['logits'])
        for l in range(3):cs[l].append(out['codes'][l]);prefix[l].append(out['prefix'][l])
    return torch.cat(parts),[torch.cat(v) for v in cs],[torch.cat(v) for v in prefix]


def protected_metrics(p,y,policy):
    rows=[];times=[]
    for a,b,route in zip(p.reshape(-1,4,10),y,policy['route']):
        t=time.perf_counter();tree=possibility_tree(a,route,5);times.append((time.perf_counter()-t)*1000)
        rows.append({'label':b.tolist(),'top1':bool((tree['sequences'][0]==b).all()),'top5':bool((tree['sequences']==b).all(-1).any())})
    return {**ap.calibration(p,y.flatten()),'sequence_top1':float(np.mean([r['top1'] for r in rows])),'sequence_top5':float(np.mean([r['top5'] for r in rows]))},rows

@torch.inference_mode()
def audit(model,z,base,target,y,policy,temp,folder,case):
    result={};normal,normal_codes,normal_prefix=predictions(model,z,target,'generated');normal_p=(normal/temp).softmax(-1)
    true=y.flatten();truth_p=normal_p.gather(1,true[:,None]).flatten();normal_correct=normal.argmax(-1)==true
    for name in ['generated','oracle0','oracle1','oracle2','oracle_all','fixed0','fixed1','fixed2','perturb0','perturb1','perturb2']:
        logits,codes,prefix=predictions(model,z,target,name);p=(logits/temp).softmax(-1)
        raw=digit_metrics(logits,y,temp);raw['correct_digit_probability']=float(p.gather(1,true[:,None]).mean())
        raw['correct_probability_delta']=float((p.gather(1,true[:,None]).flatten()-truth_p).mean())
        correct=logits.argmax(-1)==true
        raw.update(wrong_to_correct=int(((~normal_correct)&correct).sum()),correct_to_wrong=int((normal_correct&(~correct)).sum()),code_accuracy=[float((a==b).float().mean()) for a,b in zip(codes,target)])
        raw['latent_mse_to_observed']=[float((a-z).square().mean()) for a in prefix]
        raw['latent_delta_mse']=[float((a-b).square().mean()) for a,b in zip(prefix,normal_prefix)]
        fused=base.clone();fused[policy['accept']]=p[policy['accept']]
        protected,rows=protected_metrics(fused,y,policy)
        (folder/f'{case}_{name}_trace.json').write_text(json.dumps(rows))
        result[name]={'raw':raw,'protected':protected}
    coarse_right=normal_codes[0].flatten()==target[0].flatten();result['coarse_conditioned']={}
    for name,mask in [('correct',coarse_right),('incorrect',~coarse_right)]:
        result['coarse_conditioned'][name]={'n':int(mask.sum()),'generated_digit_accuracy':float(normal_correct[mask].float().mean()) if mask.any() else None}
    return result


def main():
    R.mkdir(exist_ok=True);(R/'config.json').write_text(json.dumps(CONFIG,indent=2));torch.set_num_threads(1);torch.use_deterministic_algorithms(True)
    data=load_data();tx=torch.cat([data['train'][0],clean_waveforms(data['train'][1],817)]);ty=data['train'][1].repeat(2,1)
    vx=torch.cat([data['val'][0],clean_waveforms(data['val'][1],619)]);vy=data['val'][1].repeat(2,1)
